/**
 * Combo discovery over every paper, Commander-legal card.
 *   npm run discover                 uses cached data in .cache/discovery
 *   npm run discover -- --refresh    re-download Scryfall and Commander Spellbook data
 *   npm run discover -- --limit 5000 evaluate only the first N candidates (quick runs)
 * Writes discovery/report.md and discovery/combos.json.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { toCard } from '../src/core/card.ts';
import { loadPool } from '../src/discovery/pool.ts';
import { parseAbilities } from '../src/core/abilities.ts';
import { groupFamilies } from '../src/discovery/families.ts';
import { discover, type Discovered } from '../src/discovery/search.ts';
import { loadSpellbookIndex, makeNoveltyCheck, makeVariantCheck } from '../src/discovery/spellbook-index.ts';

const args = process.argv.slice(2);
const refresh = args.includes('--refresh');
const limitArg = args.indexOf('--limit');
const limit = limitArg >= 0 ? Number(args[limitArg + 1]) : undefined;

const pool = (await loadPool({ refresh })).map((c) => toCard(c));
const index = await loadSpellbookIndex({ refresh });
const isKnown = makeNoveltyCheck(index);
const variantOf = makeVariantCheck(index);

let lastPct = -1;
const { combos, stats } = discover(pool, isKnown, {
  limit,
  variantOf,
  onProgress: (done, total) => {
    const pct = Math.floor((done / total) * 100);
    if (pct !== lastPct && pct % 10 === 0) {
      lastPct = pct;
      process.stderr.write(`  ${pct}% of ${total} candidates\n`);
    }
  },
});

const cardByName = new Map(pool.map((c) => [c.name, c]));
const families = groupFamilies(combos, (name) => (cardByName.has(name) ? parseAbilities(cardByName.get(name)!) : []));
const novelFamilies = families.filter((f) => !f.knownMember && !f.extends);
const extensionFamilies = families.filter((f) => !f.knownMember && f.extends);
const novel = combos.filter((c) => !c.known && !c.variantOf);
const variants = combos.filter((c) => !c.known && c.variantOf);
const known = combos.filter((c) => c.known);

function describe(c: Discovered): string[] {
  const per = c.verification.perLoop;
  const alternatives = Object.entries(c.helperAlternatives).map(([h, alts]) =>
    `${h} (or ${alts.slice(0, 8).join(', ')}${alts.length > 8 ? `, +${alts.length - 8} more` : ''})`,
  );
  const lines = [
    `### ${c.cards.join(' + ')}`,
    '',
    `**Produces:** ${c.produces.join(', ')}  `,
    `**Each loop (simulated):** ${[
      c.netMana !== 'none' && `+${c.netMana} mana`,
      per.deaths && `${per.deaths} deaths`,
      per.etbs && `${per.etbs} creatures entering`,
      per.tokens && `+${per.tokens} tokens`,
      per.casts && `${per.casts} spells cast`,
      per.draws && `${per.draws} cards drawn`,
      per.life && `you ${per.life > 0 ? '+' : ''}${per.life} life`,
      per.opponentLife && `opponent ${per.opponentLife} life`,
    ]
      .filter(Boolean)
      .join(' · ') || 'repeats'}  `,
  ];
  if (alternatives.length) lines.push(`**Helper:** ${alternatives.join('; ')}  `);
  if (c.prerequisites.length) lines.push(`**Needs:** ${c.prerequisites.join(' · ')}  `);
  if (c.verification.startup.length) lines.push(`**To start:** ${c.verification.startup.join(' · ')}  `);
  lines.push('', ...c.steps.map((s, i) => `${i + 1}. ${s.card}: ${s.ability} → ${s.then}.`), `${c.steps.length + 1}. Repeat.`, '');
  return lines;
}

const report = [
  '# Combo discovery',
  '',
  'Generated by `npm run discover`. Every combo below was found by the rules engine and played out by the loop',
  "simulator over the whole card pool; \"new\" means Commander Spellbook's full database has no combo with these",
  'cards. **Candidates, not confirmed combos:** each one is only as right as the rules that found it, so check it',
  'by hand (and against the current Oracle text) before sharing it.',
  '',
  `- Card pool: ${stats.poolCards} paper Commander-legal cards (${stats.loopCards} with loop abilities, ${stats.helperCards} usable as helpers)`,
  `- Spellbook database: ${index.combos.length} combos (export from ${index.timestamp})`,
  `- Candidates evaluated: ${stats.candidates.single} single cards, ${stats.candidates.pairs} pairs, ${stats.candidates.imprint} imprint pairs`,
  `- Verified combos: ${stats.combos}: ${known.length} already in Spellbook, ${variants.length} variants of a Spellbook combo (one card swapped or added), **${novel.length} new**`,
  `- Families (same pattern of roles, interchangeable cards): ${families.length}: ${families.length - novelFamilies.length - extensionFamilies.length} contain a known combo, ${extensionFamilies.length} add one piece to a known engine, **${novelFamilies.length} are new**`,
  `- Loops rejected by the simulator: ${stats.rejectedBySimulator}`,
  `- Run time: ${(stats.ms / 1000).toFixed(1)} s`,
  '',
  `## New families (${novelFamilies.length})`,
  '',
  'Each family is one idea: the roles below, with any of the listed cards in each role. One representative is shown.',
  '',
  ...novelFamilies.flatMap((f) => [
    `### ${f.members.length} combo${f.members.length === 1 ? '' : 's'}: ${f.roles.map((r) => (r.cards.length === 1 ? r.cards[0] : `[${r.cards.length} options]`)).join(' + ')}`,
    '',
    ...f.roles.map((r) => `- *${r.role}*: ${r.cards.slice(0, 10).join(', ')}${r.cards.length > 10 ? `, +${r.cards.length - 10} more` : ''}`),
    '',
    ...describe(f.members[0]!).map((l) => l.replace(/^### /, '#### Example: ')),
  ]),
  `## Variants of Spellbook combos (${variants.length})`,
  '',
  'Same idea as a known combo with one interchangeable card changed (another sacrifice outlet, another Treasure maker...).',
  '',
  ...variants.map(
    (c) =>
      `- ${c.cards.join(' + ')}: like [Spellbook ${c.variantOf!.combo.id}](https://commanderspellbook.com/combo/${c.variantOf!.combo.id}/)` +
      (c.variantOf!.theirs.length ? ` with ${c.variantOf!.ours.join(', ') || 'nothing'} instead of ${c.variantOf!.theirs.join(', ')}` : ` plus ${c.variantOf!.ours.join(', ')}`),
  ),
  '',
  `## Already in Spellbook (${known.length})`,
  '',
  ...known.map((c) => `- ${c.cards.join(' + ')} → [Spellbook ${c.known!.id}](https://commanderspellbook.com/combo/${c.known!.id}/)`),
  '',
].join('\n');

mkdirSync('discovery', { recursive: true });
writeFileSync('discovery/report.md', report);
writeFileSync('discovery/combos.json', JSON.stringify({ stats, spellbook: index.timestamp, combos }, null, 1) + '\n');
console.log(`Verified ${stats.combos} combos in ${families.length} families: ${extensionFamilies.length} extend a known engine, ${novelFamilies.length} new families. ${(stats.ms / 1000).toFixed(1)} s. Report: discovery/report.md`);
